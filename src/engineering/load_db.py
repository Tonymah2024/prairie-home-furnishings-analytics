"""Load the synthetic CSV datasets into a SQLite relational database with enforced keys, then run the SQL
validation suite (sql/validation_checks.sql). The DDL is generated from the table specs below and written to
sql/schema.sql so the schema is a reviewable deliverable."""
from __future__ import annotations

import sqlite3

import pandas as pd

from src.config import DB_PATH, SQL_DIR, SYNTH, TABLES
from src.engineering.sqlutil import load_queries

# table: (primary key, {column: referenced table(column)})   - load order respects dependencies
SPEC = {
    "suppliers": ("supplier_id", {}),
    "campaigns": ("campaign_id", {}),
    "promotions": ("promotion_id", {}),
    "staff": ("employee_id", {}),
    "store_calendar": ("date", {}),
    "products": ("product_id", {"supplier_id": "suppliers(supplier_id)"}),
    "customers": ("customer_id", {"campaign_id": "campaigns(campaign_id)"}),
    "leads": ("lead_id", {"customer_id": "customers(customer_id)"}),
    "consultations": ("consultation_id", {"customer_id": "customers(customer_id)", "designer_id": "staff(employee_id)", "order_id": "orders(order_id)"}),
    "orders": ("order_id", {"customer_id": "customers(customer_id)", "employee_id": "staff(employee_id)", "consultation_id": "consultations(consultation_id)",
                            "promotion_id": "promotions(promotion_id)"}),
    "sales_transactions": ("line_id", {"order_id": "orders(order_id)", "customer_id": "customers(customer_id)", "product_id": "products(product_id)",
                                       "employee_id": "staff(employee_id)", "promotion_id": "promotions(promotion_id)", "consultation_id": "consultations(consultation_id)"}),
    "payments": ("payment_id", {"order_id": "orders(order_id)"}),
    "purchase_orders": ("po_id", {"supplier_id": "suppliers(supplier_id)", "product_id": "products(product_id)", "order_line_id": "sales_transactions(line_id)",
                                  "replacement_of": "purchase_orders(po_id)"}),
    "inventory_movements": ("movement_id", {"product_id": "products(product_id)"}),
    "fulfillment": ("fulfillment_id", {"order_id": "orders(order_id)"}),
    "returns": ("return_id", {"line_id": "sales_transactions(line_id)", "order_id": "orders(order_id)"}),
    "stockout_events": ("stockout_id", {"product_id": "products(product_id)"}),
    "operating_expenses": ("month", {}),
    "marketing_spend": (None, {}),
}
CHECKS = {  # extra column CHECK constraints
    "sales_transactions": ["units > 0", "net_sales_cad <= gross_sales_cad + 0.01", "discount_pct >= 0 AND discount_pct < 1"],
    "orders": ["net_order_value_cad > 0", "deposit_rate > 0 AND deposit_rate <= 1"],
    "purchase_orders": ["qty_ordered > 0"],
    "products": ["list_price_cad > 0", "unit_cost_cad > 0"],
}


def sql_type(s: pd.Series) -> str:
    if pd.api.types.is_bool_dtype(s):
        return "INTEGER"
    if pd.api.types.is_integer_dtype(s):
        return "INTEGER"
    if pd.api.types.is_float_dtype(s):
        return "REAL"
    return "TEXT"


def ddl(tables: dict) -> str:
    out = ["-- Prairie Home Furnishings (fictional) - SYNTHETIC demonstration database. Generated by src/engineering/load_db.py", "PRAGMA foreign_keys = ON;", ""]
    for t, (pk, fks) in SPEC.items():
        df = tables[t]
        cols = [f'    "{c}" {sql_type(df[c])}{" PRIMARY KEY" if c == pk else ""}{" NOT NULL" if c == pk else ""}' for c in df.columns]
        cons = [f'    FOREIGN KEY ("{c}") REFERENCES {ref} DEFERRABLE INITIALLY DEFERRED' for c, ref in fks.items()]
        cons += [f"    CHECK ({c})" for c in CHECKS.get(t, [])]
        out.append(f"CREATE TABLE {t} (\n" + ",\n".join(cols + cons) + "\n);")
    out += ["CREATE INDEX ix_lines_order ON sales_transactions(order_id);", "CREATE INDEX ix_lines_product ON sales_transactions(product_id);",
            "CREATE INDEX ix_pay_order ON payments(order_id);", "CREATE INDEX ix_mv_product ON inventory_movements(product_id, inventory_state);",
            "CREATE INDEX ix_po_line ON purchase_orders(order_line_id);"]
    return "\n".join(out) + "\n"


def read_tables() -> dict:
    t = {k: pd.read_csv(SYNTH / f"{k}.csv") for k in SPEC}
    for df in t.values():
        for c in df.columns:
            if df[c].dtype == object and set(df[c].dropna().unique()) <= {True, False, "True", "False"} and df[c].notna().any():
                df[c] = df[c].map({True: 1, False: 0, "True": 1, "False": 0})
    return t


def validate(con=None) -> pd.DataFrame:
    own = con is None
    con = con or sqlite3.connect(DB_PATH)
    rows = []
    for name, q in load_queries("validation_checks.sql").items():
        n = con.execute(q).fetchone()[0]
        rows.append({"check": name, "violations": int(n or 0)})
    if own:
        con.close()
    return pd.DataFrame(rows)


def run():
    tables = read_tables()
    schema = ddl(tables)
    (SQL_DIR / "schema.sql").write_text(schema)
    if DB_PATH.exists():
        DB_PATH.unlink()
    con = sqlite3.connect(DB_PATH)
    con.executescript(schema)
    con.execute("PRAGMA foreign_keys = ON")
    cons_order = tables["consultations"][["consultation_id", "order_id"]].dropna()
    tables["consultations"] = tables["consultations"].assign(order_id=None)      # circular link set after orders are loaded
    cur = con.cursor()
    cur.execute("BEGIN")
    for name in SPEC:
        df = tables[name]
        cols = ",".join(f'"{c}"' for c in df.columns)
        cur.executemany(f"INSERT INTO {name} ({cols}) VALUES ({','.join('?' * len(df.columns))})",
                        df.astype(object).where(df.notna(), None).itertuples(index=False, name=None))
    cur.executemany("UPDATE consultations SET order_id = ? WHERE consultation_id = ?", cons_order[["order_id", "consultation_id"]].itertuples(index=False, name=None))
    con.commit()                                       # deferred FKs are enforced here, in a single transaction
    fk = con.execute("PRAGMA foreign_key_check").fetchall()
    checks = validate(con)
    counts = pd.DataFrame([(t, con.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0]) for t in SPEC], columns=["table", "rows"])
    con.close()
    checks.to_csv(TABLES / "data_validation_checks.csv", index=False)
    counts.to_csv(TABLES / "database_row_counts.csv", index=False)
    return {"checks": checks, "fk": fk, "counts": counts}


if __name__ == "__main__":
    r = run()
    print(r["counts"].to_string(index=False))
    print(r["checks"].to_string(index=False))
    print("FK violations:", len(r["fk"]))
